"""Dump the CMFT SALVE recovery grid — 4 ciphers x 2 models — to one markdown file.

Two grids over the same cells, 4 seeds each:
  z256  ->  salve/ladder_expt_<cipher>_<model>_s<seed>/   (complete, 32 cells)
  z512  ->  salve/z512_expt_<cipher>_<model>_s<seed>/     (in flight)

Output is laid out as the 4x2 grid twice: z256 block first, z512 block below,
so the same cell can be read across grids. Reads only finished artifacts, so it
is safe to re-run mid-wave.

    uv run python experiments/cmft_legibility/dump_recovered_prompts.py
"""
import json
import statistics
from pathlib import Path

import torch

SALVE = Path("/nlp/scr/nathu/cmft_legibility/salve")
OUT = Path(__file__).parent / "RECOVERED_PROMPTS.md"

CIPHERS = ["walnut50", "endspeak", "ascii", "polybius"]
MODELS = [("qwen14b", "Qwen2.5-14B"), ("gemma4_31b", "Gemma-4-31B")]
SEEDS = [42, 43, 44, 45]
GRIDS = [("z256", "ladder_expt"), ("z512", "z512_expt")]

# Three-level taxonomy, one label per recovered prompt; see prompt_labels.json
# for the definitions, the per-cell assignment, and the borderline notes. It
# replaces the earlier binary hit/miss, which fused "refusal stack that names the
# harmful topic" (L1) with "contentless echo of the decode prompt" (L0).
LABELS = json.loads((Path(__file__).parent / "prompt_labels.json").read_text())
LEVELS = ["L2", "L1", "L0"]
LEVEL_DESC = {k: LABELS["_taxonomy"][k] for k in LEVELS}


def load(cipher, model, seed, prefix):
    d = SALVE / f"{prefix}_{cipher}_{model}_s{seed}"
    if not d.is_dir():
        return None
    r = {"dir": d.name, "soft": None, "verb": None, "text": None,
         "tok": None, "imp": None, "iters": None, "depth": None}
    if (d / "soft_eval.json").exists():
        r["soft"] = json.loads((d / "soft_eval.json").read_text())["soft_train_nll"]
    if (d / "salve_beam.json").exists():
        b = json.loads((d / "salve_beam.json").read_text())
        r["verb"], r["text"], r["tok"] = b["nll"]["train"], b["best_text"], b["token_len"]
    # beam internals: improvement over the empty prompt on the selection subset,
    # which is the quantity whose seed-spread sets the resolution of this grid
    p = d / "salve_beam_results.pt"
    if p.exists():
        try:
            res = torch.load(p, map_location="cpu", weights_only=False)
            r["imp"] = res["baseline_sel"] - res["best_sel_score"]
            r["iters"] = res["n_iters"]
            el = [n for n in res["nodes"] if n.get("eligible")]
            if el:
                r["depth"] = min(el, key=lambda n: n["score"])["depth"]
        except Exception:
            pass
    return r


def fmt_cell(rs):
    """One 4x2-grid cell: aggregate over whichever seeds have finished."""
    done = [r for r in rs if r["text"]]
    if not done:
        soft = [r["soft"] for r in rs if r["soft"]]
        return f"_{len(soft)}/4 soft, 0/4 beam_" if soft else "_not started_"
    counts = {lv: sum(1 for r in done if LABELS.get(r["dir"]) == lv) for lv in LEVELS}
    tally = " ".join(f"**{lv}×{counts[lv]}**" if counts[lv] else f"{lv}×0"
                     for lv in LEVELS)
    gaps = [r["verb"] - r["soft"] for r in done]
    imps = [r["imp"] for r in done if r["imp"] is not None]
    s = f"{tally}<br>_({len(done)}/4 beam)_"
    s += f"<br>soft {min(r['soft'] for r in done):.3f}–{max(r['soft'] for r in done):.3f}"
    s += f"<br>gap {min(gaps):+.4f}–{max(gaps):+.4f}"
    if imps:
        s += f"<br>improv {min(imps):.4f}–{max(imps):.4f}"
    return s


def main():
    cells = {(c, m, g, s): load(c, m, s, pref)
             for c in CIPHERS for m, _ in MODELS
             for g, pref in GRIDS for s in SEEDS}
    cells = {k: v for k, v in cells.items() if v}

    L = ["# CMFT SALVE recovery — every recovered prompt, 4 ciphers × 2 models",
         "",
         "Generated by `dump_recovered_prompts.py`; re-run to refresh.",
         "",
         "`soft` / `verbalized` are the 317-row phase-2 train rescore; `gap` =",
         "verbalized − soft. `improv` is the beam's improvement over the empty prompt",
         "on its 64-row selection subset (`baseline_sel − best_sel_score`) — the",
         "quantity to compare against the seed-spread table below before reading",
         "anything into a single cell.",
         "",
         "**z512 cells cap sequences at `max_total_tokens=5120`; z256 cells are",
         "uncapped** (see `TRUNCATION.md`). The cap does not touch the selection",
         "subset — `baseline_sel` is identical across grids for the same cell+seed —",
         "so `improv` is comparable between grids.",
         "",
         "## Taxonomy", ""]
    for lv in LEVELS:
        L.append(f"- **{lv}** — {LEVEL_DESC[lv]}")
    L += ["", f"_{LABELS['_taxonomy']['_note']}_", ""]

    for g, _ in GRIDS:
        label = {"z256": "z256 — complete, 4 seeds/cell",
                 "z512": "z512 — in flight"}[g]
        L += [f"## Grid: {label}", "",
              "| | " + " | ".join(c for c in CIPHERS) + " |",
              "|---|" + "---|" * len(CIPHERS)]
        for m, mlabel in MODELS:
            row = [f"**{mlabel}**"]
            for c in CIPHERS:
                rs = [cells[(c, m, g, s)] for s in SEEDS if (c, m, g, s) in cells]
                row.append(fmt_cell(rs) if rs else "_not started_")
            L.append("| " + " | ".join(row) + " |")
        L.append("")
    L += ["Labels are a human reading; every prompt is reproduced in full below so",
          "the call can be checked. Borderline cases are annotated inline.", ""]

    # resolution floor
    L += ["---", "", "## Resolution: seed-spread of beam improvement", "",
          "Run-to-run spread within a single cell. Effects smaller than the spread",
          "are not readable from one seed.", "",
          "| cipher | model | grid | per-seed improvement | mean | spread |",
          "|---|---|---|---|---|---|"]
    for c in CIPHERS:
        for m, mlabel in MODELS:
            for g, _ in GRIDS:
                vals = [(s, cells[(c, m, g, s)]["imp"]) for s in SEEDS
                        if (c, m, g, s) in cells and cells[(c, m, g, s)]["imp"] is not None]
                if not vals:
                    continue
                v = [x for _, x in vals]
                L.append(f"| {c} | {mlabel} | {g} | "
                         + " ".join(f"s{s}:{x:.4f}" for s, x in vals)
                         + f" | {statistics.mean(v):.4f} | "
                         + (f"{max(v) - min(v):.4f}" if len(v) > 1 else "_n=1_") + " |")
    L.append("")

    # prompts, grid by grid, cell by cell
    for g, _ in GRIDS:
        L += ["---", "", f"# Recovered prompts — {g}", ""]
        for c in CIPHERS:
            for m, mlabel in MODELS:
                rs = [(s, cells[(c, m, g, s)]) for s in SEEDS
                      if (c, m, g, s) in cells and cells[(c, m, g, s)]["text"]]
                if not rs:
                    continue
                L += [f"## {c} × {mlabel} ({g})", ""]
                for s, r in rs:
                    lv = LABELS.get(r["dir"], "?")
                    meta = (f"**{lv}** — soft {r['soft']:.4f} → verbalized "
                            f"{r['verb']:.4f} (gap {r['verb'] - r['soft']:+.4f})")
                    if r["imp"] is not None:
                        meta += f", improv {r['imp']:.4f}, best at depth {r['depth']}/{r['iters']}"
                    L += [f"**seed {s}** — {meta}, {r['tok']} tokens", ""]
                    note = LABELS.get("_borderline", {}).get(r["dir"])
                    if note:
                        L += [f"> ⚖️ borderline: {note}", ""]
                    L += ["```text", r["text"].strip(), "```", ""]

    OUT.write_text("\n".join(L))
    done = sum(1 for r in cells.values() if r["text"])
    print(f"wrote {OUT} ({done} prompts, {len(cells) - done} cells pending)")


if __name__ == "__main__":
    main()
