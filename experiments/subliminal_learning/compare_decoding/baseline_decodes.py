"""Non-soft-prompt verbalization baselines for the val-NLL-vs-catness plot.

`sample_score_decodes.py` asks: across verbalizations of one trained soft
prompt, does val NLL track catness? This script adds the *reference sources* —
verbalizations that do NOT come from a trained soft prompt — so we can see where
"base + soft prompt" sits relative to the floor and the finetune skyline. No
search (single-shot decodes), single temperature (default 0.7).

Three sources, each verbalized through the SAME decode templates + scored the
SAME way as the soft decodes (every candidate is judged as a *base-model system
prompt* by val NLL on the number completions + teacher-forced mean logP(label)):

  base_empty          : empty soft slot, generated by the BASE model. The
                        "default prompt" floor — what the verbalizer emits with
                        no trait signal to recover.
  finetune            : empty soft slot, generated by the vanilla SFT adapter
                        (the producer's model organism M_ft). Asks the finetune
                        to "write its system prompt" — the trait is subliminal,
                        so this probes whether it verbalizes at all.
  ft_base_contrastive : (1+a)*logits_ft - a*logits_base over identical (empty-
                        slot) embeds, sweeping a small alpha grid. Amplifies what
                        the finetune adds over base in token space.

Scoring is always on the frozen BASE model; the finetune is loaded as a second
instance (PEFT) used only as a verbalization generator, so the scoring base
stays pristine (never adapter-wrapped). Reuses the val NLL objective + the
cat-logprob proxy verbatim from the soft-decode script.

  PYTHONUNBUFFERED=1 PYTHONPATH=. uv run python \\
    experiments/subliminal_learning/compare_decoding/baseline_decodes.py \\
    --run-dir /nlp/scr/nathu/latent_rewrite/subliminal_learning/steered_cat_e4_lr1e-3 \\
    --gpu 0
"""
import argparse
import json
import math
import statistics
import sys
from pathlib import Path

import torch

sys.path.insert(0, str(Path(__file__).resolve().parents[3]))  # repo root

from peft import PeftModel

from core.models import load_frozen_lm
from optimize.objectives.nll import nll_objective_from_xys
from optimize.template_factories.sysprompt import build_sysprompt_template
from optimize.recover import build_decode_optimizer

from experiments.subliminal_learning.data import (
    load_sl_splits, load_eval_spec, sl_adapter_path)
from experiments.subliminal_learning.compare_decoding.sample_score_decodes import (
    cat_logprob)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-dir", required=True, help="dir with soft_z.pt")
    ap.add_argument("--n", type=int, default=12,
                    help="decodes per source (and per alpha for contrastive)")
    ap.add_argument("--temp", type=float, default=0.7, help="verbalize temperature")
    ap.add_argument("--alphas", type=float, nargs="+", default=[0.25, 0.5, 1.0],
                    help="ft-vs-base contrastive alpha grid")
    ap.add_argument("--max-val", type=int, default=None,
                    help="cap val examples scored (default: full val split)")
    ap.add_argument("--n-eval-prompts", type=int, default=None,
                    help="cap producer eval prompts for cat-logprob (default: all)")
    ap.add_argument("--gpu", type=int, default=0)
    ap.add_argument("--output", default=None,
                    help="default <run-dir>/baseline_decodes.json")
    args = ap.parse_args()

    device = f"cuda:{args.gpu}"
    run = Path(args.run_dir)
    soft = torch.load(run / "soft_z.pt", map_location="cpu", weights_only=False)
    cfg = soft["config"]
    condition, topic = cfg["data"]["condition"], cfg["data"]["topic"]
    n_learnable = cfg["n_learnable"]

    model, tokenizer, embed_matrix = load_frozen_lm(cfg["model"], device=device)

    # Finetune (M_ft) on a SECOND base instance so scoring's base stays pristine
    # (PEFT mutates its base in place — never wrap the scoring model).
    adapter_path = sl_adapter_path(condition, topic)
    print(f"loading finetune adapter: {adapter_path}", flush=True)
    ft_base, _, _ = load_frozen_lm(cfg["model"], device=device)
    ft_model = PeftModel.from_pretrained(ft_base, str(adapter_path)).eval()

    # --- val NLL objective on the base (same loader/splits as run.py) ---
    xy = load_sl_splits(**cfg["data"], seed=cfg["seed"])
    if args.max_val is not None:
        xy["val"] = xy["val"][:args.max_val]
    build = lambda s, r, target_ids=None: build_sysprompt_template(
        tokenizer, s, r, n_learnable=n_learnable,
        system_template=cfg["system_template"], target_ids=target_ids)
    nll_obj = nll_objective_from_xys(
        model, tokenizer, xy, build, system_template=cfg["system_template"])
    n_val = len(nll_obj.xy_by_split["val"])

    label, eval_prompts = load_eval_spec(topic)
    if args.n_eval_prompts is not None:
        eval_prompts = eval_prompts[:args.n_eval_prompts]
    print(f"condition={condition} topic={topic} label={label!r} "
          f"n_val={n_val} n_eval_prompts={len(eval_prompts)}", flush=True)

    def score_text(text):
        return {
            "nll_val": float(nll_obj.hard_loss(text, "val", mini_batch_size=16)),
            "cat_logprob": cat_logprob(
                model, tokenizer, eval_prompts, label,
                kind="text", system_text=text),
        }

    # Empty soft slot: a (0, hidden) tensor threads through _decode's slot
    # assembly as a no-op, giving the empty-system framing for every source.
    z_empty = torch.zeros(0, embed_matrix.shape[1],
                          device=device, dtype=embed_matrix.dtype)

    decode_opt = build_decode_optimizer(
        cfg["decode"], embed_matrix, nll_obj, model, tokenizer)
    decode_opt.config.decode_temperature = float(args.temp)
    templates = decode_opt.decode_templates
    print(f"{len(templates)} decode templates ({cfg['decode']['pool']}) "
          f"@ T={args.temp}", flush=True)

    # (source tag, gen_model, neg_model, contrastive_alpha) per decode batch.
    jobs = [("base_empty", model, None, None),
            ("finetune", ft_model, None, None)]
    for a in args.alphas:
        jobs.append(("ft_base_contrastive", ft_model, model, float(a)))

    torch.manual_seed(cfg["seed"])
    torch.cuda.manual_seed_all(cfg["seed"])
    records = []
    for source, gen_model, neg_model, alpha in jobs:
        atag = "" if alpha is None else f" α={alpha}"
        print(f"--- source={source}{atag} ---", flush=True)
        for k in range(args.n):
            ti = k % len(templates)
            tmpl = templates[ti]
            raw, _ = decode_opt._decode(
                z_empty, tmpl={**tmpl, "postprocess": None}, max_tokens=n_learnable,
                contrastive_alpha=alpha, gen_model=gen_model, neg_model=neg_model)
            post = tmpl.get("postprocess")
            cleaned = post(raw) if post else raw
            if not cleaned:
                cleaned = raw
            rec = {
                "source": source,
                "contrastive_alpha": alpha,
                "temperature": float(args.temp),
                "template_idx": ti,
                "decode_user": tmpl.get("user"),
                "decode_prefill": tmpl.get("prefill"),
                "raw_text": raw,
                "cleaned_text": cleaned,
                **score_text(cleaned),
            }
            records.append(rec)
            print(f"  {source}{atag} tmpl{ti}: nll={rec['nll_val']:.4f} "
                  f"catlp={rec['cat_logprob']:.3f} :: {cleaned[:70]!r}", flush=True)

    # Per-source summary (mean over its decodes).
    print("\n=== baseline source summaries ===")
    for source, _, _, alpha in jobs:
        rs = [r for r in records if r["source"] == source
              and r["contrastive_alpha"] == alpha]
        atag = "" if alpha is None else f" α={alpha}"
        nll = statistics.fmean(r["nll_val"] for r in rs)
        clp = statistics.fmean(r["cat_logprob"] for r in rs)
        print(f"  {source}{atag}: mean nll={nll:.4f} mean catlp={clp:.3f} "
              f"(cat_prob={math.exp(clp):.4f}) [n={len(rs)}]")

    out_json = Path(args.output) if args.output else run / "baseline_decodes.json"
    out_json.write_text(json.dumps({
        "run_dir": str(run),
        "condition": condition,
        "topic": topic,
        "label": label,
        "adapter_path": str(adapter_path),
        "temperature": float(args.temp),
        "alphas": list(args.alphas),
        "n_val": n_val,
        "n_eval_prompts": len(eval_prompts),
        "n_learnable": n_learnable,
        "baseline_decodes": records,
    }, indent=2))
    print(f"\nsaved → {out_json}")


if __name__ == "__main__":
    main()
